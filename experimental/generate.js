// Writes docker/compose.yml and k8s/breakshop.yaml from topology.json. Experimental: never run against a real engine yet.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const topo = JSON.parse(fs.readFileSync(path.join(root, 'topology.json'), 'utf8'));
const names = topo.profiles.full;
const fixed = JSON.stringify(Object.fromEntries(names.map((n) => [n, [{ host: n, port: topo.processes[n].port }]])));
const cc = `http://control-center:${topo.processes['control-center'].port}`;

const env = (n) => ({
  BS_HOST: '0.0.0.0', BS_PORT: String(topo.processes[n].port), BS_INSTANCE: `${n}-0`, BS_DATA_DIR: '/data',
  BS_ALLOWED_HOSTS: names.join(','), BS_STATIC_DIRECTORY: fixed, BS_CONTROL_CENTER_URL: cc,
  BS_PROFILE: 'full', BS_JOURNEYS: topo.journeys.full.join(',')
});

const compose = ['# EXPERIMENTAL AND UNTESTED. Generated by experimental/generate.js.', 'services:'];
for (const n of names) {
  const p = topo.processes[n];
  compose.push(`  ${n}:`, '    build:', '      context: ../..', '      dockerfile: experimental/docker/Dockerfile', `    command: ["${p.entry}"]`, '    environment:');
  for (const [k, v] of Object.entries(env(n))) compose.push(`      ${k}: '${v.replace(/'/g, "''")}'`);
  compose.push('    ports:', `      - "${p.port}:${p.port}"`, '    volumes:', '      - data:/data');
}
compose.push('volumes:', '  data: {}');

const k8s = ['# EXPERIMENTAL AND UNTESTED. Generated by experimental/generate.js.'];
for (const n of names) {
  const p = topo.processes[n];
  k8s.push('---', 'apiVersion: apps/v1', 'kind: Deployment', `metadata: { name: ${n}, labels: { app: ${n} } }`,
    'spec:', '  replicas: 1', `  selector: { matchLabels: { app: ${n} } }`, '  template:', `    metadata: { labels: { app: ${n} } }`,
    '    spec:', '      containers:', `        - name: ${n}`, '          image: breakshop:latest', '          imagePullPolicy: Never',
    `          args: ["${p.entry}"]`, `          ports: [{ containerPort: ${p.port} }]`, '          env:');
  for (const [k, v] of Object.entries(env(n))) k8s.push(`            - { name: ${k}, value: '${v.replace(/'/g, "''")}' }`);
  k8s.push('---', 'apiVersion: v1', 'kind: Service', `metadata: { name: ${n} }`, 'spec:', `  selector: { app: ${n} }`, `  ports: [{ port: ${p.port}, targetPort: ${p.port} }]`);
}

fs.writeFileSync(path.join(__dirname, 'docker', 'compose.yml'), compose.join('\n') + '\n');
fs.writeFileSync(path.join(__dirname, 'k8s', 'breakshop.yaml'), k8s.join('\n') + '\n');
console.log(`wrote compose and k8s files for ${names.length} processes`);
